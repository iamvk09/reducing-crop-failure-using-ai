export function localize_value(value: string | number | null | undefined, lang: string = "en"): string {
  if (value === null || value === undefined) return "";
  const str = String(value);
  return VALUE_TRANSLATIONS[lang]?.[str] || str;
}

export function localize_feature(feature: string, lang: string = "en"): string {
  return FEATURE_TRANSLATIONS[lang]?.[feature] || feature;
}

export function t(key: keyof TranslationDict, lang: string = "en"): string {
  const current = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return current[key] || TRANSLATIONS.en[key] || key;
}
